public class Point2D {
    private double coordX;
    private double coordY;

    public Point2D(double x, double y) {
        this.coordX = x;
        this.coordY = y;
    }

    public double getX() {
        return coordX;
    }

    public void setX(double x) {
        this.coordX = x;
    }

    public double getY() {
        return coordY;
    }

    public void setY(double y) {
        this.coordY = y;
    }
}
